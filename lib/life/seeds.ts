async function addLeadNotes({ notes, follow_up_date, status, ...lead }: SeedLeadNotes, today: string) {
  const leads = getLeadsStore();
  const phone = intlPhone(lead.phone);
  const found = (await leads.list()).find((l) => phone && intlPhone(l.phone) === phone);
  if (!found) {
    await leads.add({ ...lead, notes: notes ?? null, follow_up_date: follow_up_date ?? today, source: "outreach", ...(status ? { status } : {}) });
    return;
  }
  // Notes already there (an earlier batch with the same text) are not added twice.
  const firstLine = notes?.split("\n")[0] ?? "";
  const merged = !notes || found.notes?.includes(firstLine) ? found.notes : [found.notes, notes].filter(Boolean).join("\n\n");
  await leads.update(found.id, { notes: merged, ...(follow_up_date ? { follow_up_date } : {}), ...(status ? { status } : {}) });
}

export async function applySeeds(store: LifeStore) {
  const applied = (await store.getDoc<{ applied: string[] }>("seeds"))?.applied ?? [];
  const pending = SEEDS.filter((batch) => !applied.includes(batch.id));
  if (!pending.length) return;
  // Recorded before inserting, so two requests at once cannot both add the same items.
  await store.saveDoc("seeds", { applied: [...applied, ...pending.map((b) => b.id)] });
  const ideas = getIdeasStore();
  const today = israelToday();
  const now = toMinutes(israelNow());
  for (const batch of pending) {
    if (batch.settings) await store.saveSettings(batch.settings);
    if (batch.leads?.length || batch.leadNotes?.length) {
      // The leads table comes with the site SQL; if it is not there yet, try again next time.
      try {
        for (const lead of batch.leads ?? []) await getLeadsStore().add({ ...lead, follow_up_date: today, source: "outreach" });
        for (const entry of batch.leadNotes ?? []) await addLeadNotes(entry, today);
      } catch (error) {
        console.error("[life/seeds] leads", error);
        const now = (await store.getDoc<{ applied: string[] }>("seeds"))?.applied ?? [];
        await store.saveDoc("seeds", { applied: now.filter((id) => id !== batch.id) });
        continue;
      }
    }
    // A reminder whose time already passed (e.g. seeded after connecting late) is skipped, not
    // sent late all at once.
    for (const lesson of batch.lessons ?? []) await getLessonsStore().add(lesson);
    for (const { tasks, invite_text, ...input } of batch.events ?? []) {
      if (input.date < today) continue;
      const event = await store.addEvent({ ...input, end_time: input.end_time ?? null });
      for (const t of tasks ?? []) await store.addTask({ ...t, area: t.area ?? input.area, event_id: event.id });
      if (invite_text) await setInviteText(store, event.id, invite_text);
    }
    for (const { plan, ...goal } of batch.goals ?? []) {
      let planId: string | null = null;
      if (plan) {
        const { status, steps, ...input } = plan;
        const idea = await ideas.add(input);
        await ideas.update(idea.id, {
          ...(status ? { status } : {}),
          ...(steps?.length ? { steps: steps.map((text) => ({ id: crypto.randomUUID(), text, done: false })) } : {}),
        });
        planId = idea.id;
      }
      await appendGoal(store, { ...goal, start_date: today, plan_idea_id: planId });
    }
    for (const { date, titleIncludes, tasks } of batch.eventTasks ?? []) {
      // If the event was deleted meanwhile, the tasks still come, just not linked to it.
      const event = (await store.listEvents(date)).find((e) => e.title.includes(titleIncludes));
      for (const t of tasks) await store.addTask({ ...t, area: t.area ?? event?.area, event_id: event?.id ?? null });
    }
    for (const r of batch.reminders ?? []) {
      if (r.date > today || (r.date === today && toMinutes(r.time) > now)) await addReminder(store, r);
    }
    for (const r of batch.reminderResults ?? []) {
      const found = (await loadReminders(store)).find((x) => x.date === r.date && x.text.includes(r.textIncludes));
      if (found) await updateReminder(store, found.id, { text: r.text });
    }
    for (const { status, steps, ...input } of batch.ideas ?? []) {
      const idea = await ideas.add(input);
      if (status || steps?.length) {
        await ideas.update(idea.id, {
          ...(status ? { status } : {}),
          ...(steps?.length ? { steps: steps.map((text) => ({ id: crypto.randomUUID(), text, done: false })) } : {}),
        });
      }
    }
  }
}
