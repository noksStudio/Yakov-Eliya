export function matchAssistant(message: string): AssistantEntry {
  const normalized = message.trim();
  if (!normalized) return fallback;

  let best: AssistantEntry | null = null;
  let bestScore = 0;

  for (const entry of assistantKB) {
    const score = entry.keywords.reduce(
      (acc, kw) => (normalized.includes(kw) ? acc + kw.length : acc),
      0
    );
    if (score > bestScore) {
      bestScore = score;
      best = entry;
    }
  }

  return best ?? fallback;
}

